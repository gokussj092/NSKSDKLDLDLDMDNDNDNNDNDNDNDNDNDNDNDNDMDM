internal enum class AdminLanguage(val tag: String, val nativeName: String) {
  Es("es", "Español"), En("en", "English");
  companion object {
    fun fromTag(tag: String?) = entries.firstOrNull { it.tag == tag } ?: Es
  }
}

private val LocalAdminResources = staticCompositionLocalOf<Resources?> { null }

@Composable
internal fun AdminLocaleProvider(language: AdminLanguage, content: @Composable () -> Unit) {
  val context = LocalContext.current
  val baseConfiguration = LocalConfiguration.current
  val resources = remember(context, language, baseConfiguration) {
    val configuration = Configuration(baseConfiguration)
    configuration.setLocale(Locale.forLanguageTag(language.tag))
    context.createConfigurationContext(configuration).resources
  }
  CompositionLocalProvider(LocalAdminResources provides resources, content = content)
}

