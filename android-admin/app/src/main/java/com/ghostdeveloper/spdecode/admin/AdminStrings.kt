@Composable
internal fun L(label: String): String {
  val resources = LocalAdminResources.current ?: return label
  val id = labelsByText[label] ?: return label
  return resources.getString(id)
}

@Composable
internal fun LF(label: String, vararg values: Any): String =
    String.format(Locale.ROOT, L(label), *values)

@Composable
internal fun AdminErrorLabel(message: String): String {
  val prefix = "No se pudo completar la operación ("
  return if (message.startsWith(prefix) && message.endsWith(")."))
    LF("No se pudo completar la operación (%1\$s).", message.removePrefix(prefix).removeSuffix(")."))
  else L(message)
}
