"""Generate Python-reference Unicode predicates for the historical HC port."""
from pathlib import Path
import unicodedata

ROOT = Path(__file__).resolve().parents[4]
TARGET = ROOT / "android/app/src/main/cpp/spdecode_hc_unicode.h"

def ranges(predicate):
    start = None
    for cp in range(0x110001):
        hit = cp < 0x110000 and predicate(chr(cp))
        if hit and start is None:
            start = cp
        if not hit and start is not None:
            yield start, cp - 1
            start = None

def main():
    assert unicodedata.unidata_version == "15.0.0", "Reference Unicode version changed"
    text = ["// Generated by analysis/_intake/httpcustom-offline-20261109/tools/build_unicode_properties.py",
            "// Python Unicode 15.0.0 predicates; no locale-dependent classification.",
            "#pragma once", "#include <cstdint>", "#include <cstddef>",
            "namespace spdecode::offline::hcunicode {", "struct Range {uint32_t first,last;};"]
    for name, predicate in (("printable", str.isprintable), ("alnum", str.isalnum)):
        values = list(ranges(predicate))
        text.append(f"inline constexpr Range {name}Ranges[]={{")
        for i in range(0, len(values), 6):
            text.append("    " + ",".join(f"{{0x{a:x},0x{b:x}}}" for a,b in values[i:i+6]) + ",")
        text.append("};")
    text += ["template<size_t N> inline bool contains(const Range (&ranges)[N],uint32_t cp){",
             "    size_t lo=0,hi=N;",
             "    while(lo<hi){const size_t mid=lo+(hi-lo)/2;",
             "        if(cp<ranges[mid].first)hi=mid;",
             "        else if(cp>ranges[mid].last)lo=mid+1;else return true;}",
             "    return false;", "}", "}"]
    TARGET.write_text("\n".join(text)+"\n")

if __name__ == "__main__":
    main()
