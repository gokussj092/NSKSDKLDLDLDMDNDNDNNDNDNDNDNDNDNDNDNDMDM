#!/usr/bin/env python3
"""1FTunnel 0.7.3 dossier tests (analysis/com.oneftunnel.app/129/tests).

Run from the repo root:
    python -m unittest discover -s analysis/com.oneftunnel.app/129/tests -v

The synthetic fixture tests/fixtures/v6_password.1ftnl is generated by
tools/make_fixture_v6.py (fixed salt/nonce, dummy example.org values,
password "test-only" — a test vector, not a real credential). The v1-v5
fixtures tests/fixtures/vN_password.1ftnl are generated by
tools/make_fixtures_v1_v5.py and pin Pedro's hard requirement: the codec.py
fix ADDS CFG1 v6 support without removing v1-v5. The real user
file is NEVER used here; the positive real-file check lives in
tools/verify_073.py and takes the password from ONEFT_PW.
"""
from __future__ import annotations

import importlib.util
import json
import sys
import unittest
from pathlib import Path

HERE = Path(__file__).resolve().parent
DOSSIER = HERE.parent
REPO = DOSSIER.parents[2]  # 129 -> com.oneftunnel.app -> analysis -> repo root
DECODER_DIR = REPO / "decoders" / "Python" / "apps" / "OneFTunnel"

sys.path.insert(0, str(DECODER_DIR))


def _load(name: str):
    spec = importlib.util.spec_from_file_location(name, DECODER_DIR / (name + ".py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


FT = _load("1FTunnel")
FD = _load("file_decoder")
CODEC = _load("codec")
FIXTURE = HERE / "fixtures" / "v6_password.1ftnl"
EXPECTED = json.loads((HERE / "fixtures" / "v6_password.expected.json").read_text())


class TestMethod073(unittest.TestCase):
    def test_repo_self_test(self):
        """The repo decoder's own 12-check self-test still passes."""
        self.assertTrue(FT._self_test())

    def test_fixture_v6_password_opens(self):
        """Synthetic CFG1 v6 + lockMode 2 opens with the fixture password."""
        text = FIXTURE.read_text(encoding="utf-8")
        result = FT.decode(text, password=EXPECTED["password"])
        self.assertEqual(result["format"], "1FT1")
        self.assertTrue(result["metadata"]["authenticated"])
        self.assertFalse(result["isPartial"])
        self.assertEqual(result["metadata"]["configType"], "SSH")
        self.assertEqual(result["metadata"]["lockMode"], 2)
        self.assertEqual(result["metadata"]["keySlot"], 1)
        self.assertEqual(result["metadata"]["minimumAppBuild"], 129)
        self.assertEqual(result["config"]["payloadVersion"], 6)
        self.assertEqual(result["config"]["inject"]["mode"], "SLOWDNS")
        self.assertEqual(result["config"]["slowDns"]["recordType"], "A")

    def test_fixture_v6_password_required(self):
        """Same fixture without password reports PASSWORD_REQUIRED."""
        text = FIXTURE.read_text(encoding="utf-8")
        with self.assertRaises(FT.DecodeError) as ctx:
            FT.decode(text)
        self.assertEqual(ctx.exception.code, "PASSWORD_REQUIRED")

    def test_fixture_v6_wrong_password(self):
        """Same fixture with a wrong password fails GCM authentication."""
        text = FIXTURE.read_text(encoding="utf-8")
        with self.assertRaises(FT.DecodeError) as ctx:
            FT.decode(text, password="wrong-password")
        self.assertEqual(ctx.exception.code, "AUTH_FAILED")

    def test_worker_path_opens_v6_text(self):
        """The server worker path (file_decoder -> codec.py) now opens CFG1 v6.

        Regression test for the codec.py fix: the worker previously rejected
        v6 with UNSUPPORTED_PAYLOAD_VERSION even with the correct password.
        """
        text = FIXTURE.read_text(encoding="utf-8")
        result = json.loads(
            FD.run(text.encode("utf-8"), password=EXPECTED["password"]))
        self.assertEqual(result["format"], "1FT1")
        self.assertTrue(result["metadata"]["authenticated"])
        self.assertFalse(result["isPartial"])
        self.assertEqual(result["config"]["payloadVersion"], 6)
        self.assertEqual(result["config"]["inject"]["mode"], "SLOWDNS")
        self.assertEqual(result["config"]["slowDns"]["recordType"], "A")

    def test_worker_path_opens_v1_v5_no_regression(self):
        """CFG1 v1-v5 keep opening through the worker path after the fix.

        Pedro's hard requirement: the fix ADDS v6 support; it must not
        remove any earlier version. Each synthetic fixture opens via the
        exact worker entry point (file_decoder.run) and via codec.decode
        directly, and both agree with the reference decoder (1FTunnel).
        """
        for version in (1, 2, 3, 4, 5):
            with self.subTest(version=version):
                fixture = HERE / "fixtures" / f"v{version}_password.1ftnl"
                expected = json.loads(
                    (HERE / "fixtures" /
                     f"v{version}_password.expected.json").read_text())
                text = fixture.read_text(encoding="utf-8")
                worker = json.loads(
                    FD.run(text.encode("utf-8"),
                           password=expected["password"]))
                direct = CODEC.decode(text, password=expected["password"])
                reference = FT.decode(text, password=expected["password"])
                for result in (worker, direct, reference):
                    self.assertEqual(
                        result["config"]["payloadVersion"], version)
                    self.assertTrue(result["metadata"]["authenticated"])
                    self.assertFalse(result["isPartial"])
                    self.assertEqual(result["metadata"]["configType"],
                                     expected["configType"])
                # Worker codec omits "slowDns" below v6 (v1-v5 JSON contract
                # unchanged); the reference always emits it (None).
                self.assertEqual(
                    {k: v for k, v in worker["config"].items()
                     if k != "slowDns"},
                    {k: v for k, v in reference["config"].items()
                     if k != "slowDns"})
                self.assertEqual(
                    {k: v for k, v in direct["config"].items()
                     if k != "slowDns"},
                    {k: v for k, v in reference["config"].items()
                     if k != "slowDns"})
                self.assertIsNone(reference["config"]["slowDns"])
                self.assertNotIn("slowDns", worker["config"])
                self.assertNotIn("slowDns", direct["config"])
                if expected["injectMode"] is not None:
                    self.assertEqual(worker["config"]["inject"]["mode"],
                                     expected["injectMode"])
                else:
                    self.assertIsNone(worker["config"]["inject"])
                self.assertEqual(
                    {k: (worker["config"].get(k) is not None)
                     for k in ("ssh", "inject", "dns", "xray", "slowDns")},
                    expected["sections"])

    def test_fixture_tampered(self):
        """Flipping one ciphertext byte fails GCM authentication."""
        text = FIXTURE.read_text(encoding="utf-8").strip()
        body = text[len("1FTnl."):]
        tampered = body[:-5] + ("A" if body[-5] != "A" else "B") + body[-4:]
        with self.assertRaises(FT.DecodeError) as ctx:
            FT.decode("1FTnl." + tampered, password=EXPECTED["password"])
        self.assertEqual(ctx.exception.code, "AUTH_FAILED")

    def test_fixture_matches_expected(self):
        """Fixture file hash and structure match the recorded expectation."""
        import hashlib
        digest = hashlib.sha256(FIXTURE.read_bytes()).hexdigest()
        self.assertEqual(
            digest,
            "aa4c451b9c99698025414efcd84a5a45a24e7e8d26604027e87baeb79a80de48")
        self.assertEqual(EXPECTED["payloadVersion"], 6)
        self.assertEqual(EXPECTED["minimumAppBuild"], 129)


if __name__ == "__main__":
    unittest.main()
