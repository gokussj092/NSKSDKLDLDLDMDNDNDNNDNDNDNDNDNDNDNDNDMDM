#!/usr/bin/env python3
"""Generate SP-DECODE's three-host HTTPS reverse proxy without exposing worker/admin.

Public web: DOMAIN + optional www; Android API: api.DOMAIN; admin: panel.DOMAIN.
Backend is one Next.js service on 127.0.0.1:3000, routed by virtual host.
"""
from __future__ import annotations

import argparse
import ipaddress
import re


def hostname(value: str) -> str:
    value = value.lower()
    if (len(value) > 253 or not re.fullmatch(
        r"[a-z0-9](?:[a-z0-9.-]{0,251}[a-z0-9])?", value
    ) or "." not in value or ".." in value or value.endswith(".local")
            or any(not 1 <= len(label) <= 63 or label.startswith("-")
                   or label.endswith("-") for label in value.split("."))):
        raise ValueError("Invalid DNS hostname")
    return value


def exact_ip_cidr(value: str) -> str:
    network = ipaddress.ip_network(value, strict=True)
    if network.prefixlen != network.max_prefixlen:
        raise ValueError("Admin must be restricted to one IP (/32 or /128)")
    return str(network)


def common_headers() -> str:
    return '''    proxy_pass http://127.0.0.1:3000;
    proxy_http_version 1.1;
    proxy_set_header Host $host;
    proxy_set_header X-Real-IP $remote_addr;
    proxy_set_header X-Forwarded-For $remote_addr;
    proxy_set_header X-Forwarded-Proto https;
    proxy_set_header Connection "";
    proxy_connect_timeout 5s;
    proxy_send_timeout 25s;
    proxy_read_timeout 35s;
    proxy_redirect off;'''


def generate(domain: str, api: str, panel: str, cidr: str, www: bool) -> str:
    domain, api, panel = map(hostname, (domain, api, panel))
    if api == panel or api == domain or panel == domain:
        raise ValueError("Web, API and admin must use distinct hostnames")
    if not api.endswith("." + domain) or not panel.endswith("." + domain):
        raise ValueError("API and admin must be subdomains of the web domain")
    ip = exact_ip_cidr(cidr)
    cert = f"/etc/letsencrypt/live/{domain}"
    header = lambda host: f'''    listen 443 ssl;
    server_name {host};
    ssl_certificate {cert}/fullchain.pem;
    ssl_certificate_key {cert}/privkey.pem;
    ssl_protocols TLSv1.2 TLSv1.3;
    client_max_body_size 12m;
    client_body_timeout 25s;
    client_header_timeout 10s;
    keepalive_timeout 10s;
    server_tokens off;
    add_header Strict-Transport-Security "max-age=31536000" always;
    add_header X-Content-Type-Options "nosniff" always;
    add_header Referrer-Policy "no-referrer" always;'''
    www_name = f"www.{domain}"
    http_hosts = " ".join([domain, api, panel] + ([www_name] if www else []))
    output = [
        "# Generated by SP-DECODE C8; do not edit from the public web container.",
        f'''server {{
    listen 80;
    server_name {http_hosts};
    root /var/www/spdecode-acme;
    location ^~ /.well-known/acme-challenge/ {{ try_files $uri =404; }}
    location / {{ return 308 https://{domain}$request_uri; }}
}}''',
        f'''server {{
{header(domain)}
    # The public site cannot call administrative or decoding endpoints.
    location ^~ /admin {{ return 404; }}
    location ^~ /api/admin {{ return 404; }}
    location ^~ /api/v1/ {{ return 404; }}
    location / {{
{common_headers()}
    }}
}}''',
        f'''server {{
{header(api)}
    # Android-only API; no public website or operator panel on this host.
    location ^~ /api/v1/ {{
        access_log off;
{common_headers()}
    }}
    location / {{ return 404; }}
}}''',
        f'''server {{
{header(panel)}
    # Default localhost-only access until --admin-cidr OPERATOR_IP/32.
    allow {ip};
    deny all;
    access_log off;
    location = / {{ return 302 /admin/login; }}
    location ^~ /admin {{
{common_headers()}
    }}
    location ^~ /api/admin/ {{
{common_headers()}
    }}
    # Next.js admin scripts and styles. No public decoding API accessible.
    location ^~ /_next/ {{
{common_headers()}
    }}
    location / {{ return 404; }}
}}''',
    ]
    if www:
        output.append(f'''server {{
{header(www_name)}
    return 308 https://{domain}$request_uri;
}}''')
    return "\n".join(output) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("domain", help="Public website hostname, e.g. spdecode.xyz")
    parser.add_argument("admin_cidr", nargs="?", default="127.0.0.1/32",
                        help="Exact operator IP (never 0.0.0.0/0)")
    parser.add_argument("--api-domain", default=None)
    parser.add_argument("--panel-domain", default=None)
    parser.add_argument("--www", action="store_true")
    args = parser.parse_args()
    domain = hostname(args.domain)
    api = args.api_domain or "api." + domain
    panel = args.panel_domain or "panel." + domain
    try:
        print(generate(domain, api, panel, args.admin_cidr, args.www), end="")
    except ValueError as exc:
        parser.error(str(exc))


if __name__ == "__main__":
    main()
