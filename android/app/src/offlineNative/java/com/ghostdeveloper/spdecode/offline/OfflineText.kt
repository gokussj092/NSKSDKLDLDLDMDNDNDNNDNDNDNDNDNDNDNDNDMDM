internal fun txt(key:String,language:String):String {
    val locale=Locale.getDefault()
    val chosen=if(language=="system") {
        if(locale.language=="pt"&&locale.country.equals("BR",true))"pt-BR"
        else if(locale.language=="in")"id"
        else locale.language
    }else language
    return translated[chosen]?.get(key)?:translated["en"]?.get(key)?:key
}
